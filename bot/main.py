def queue_message_for_hermes(channel_id: int, channel_name: str, user: str, message: str) -> str:
    """Queue a message for Hermes to process. Returns the queue file path."""
    session = get_session(channel_id)
    instruction_file = get_instruction_file(session)

    payload = {
        "timestamp": datetime.utcnow().isoformat(),
        "session": session,
        "channel_id": channel_id,
        "channel_name": channel_name,
        "user": user,
        "message": message,
        "instruction_file": instruction_file,
        "status": "pending",
        "id": f"{channel_id}_{int(datetime.utcnow().timestamp() * 1000)}",
    }

    queue_file = QUEUE_DIR / f"{payload['id']}.json"
    with open(queue_file, "w") as f:
        json.dump(payload, f, indent=2)

    return str(queue_file)


async def check_hermes_response(queue_file: str) -> str | None:
    """Check if Hermes has responded to a queued message."""
    response_file = Path(queue_file).with_suffix(".response.json")
    if response_file.exists():
        with open(response_file) as f:
            data = json.load(f)
        # Clean up
        response_file.unlink(missing_ok=True)
        Path(queue_file).unlink(missing_ok=True)
        return data.get("response", "No response content.")
    return None


def read_operator_token() -> str:
    """Read the local operator bearer token generated by Agent OS."""
    try:
        with open(OPERATOR_TOKEN_FILE, encoding="utf-8") as f:
            data = json.load(f)
        return str(data.get("token") or "")
    except (OSError, json.JSONDecodeError):
        return ""


def fetch_operator_inspect(project: str) -> tuple[int, dict]:
    """Call the read-only operator inspect endpoint with the bearer token."""
    return operator_request("GET", f"/api/operator/inspect?project={urllib.parse.quote(project)}")


def operator_request(method: str, path: str, payload: dict | None = None) -> tuple[int, dict]:
    """Call an authenticated operator endpoint and return status + JSON payload."""
    token = read_operator_token()
    if not token:
        return 0, {"ok": False, "error": "operator token missing"}
    body = None
    headers = {"Authorization": f"Bearer {token}"}
    if payload is not None:
        body = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(OPERATOR_API_URL + path, data=body, headers=headers, method=method.upper())
    try:
        with urllib.request.urlopen(request, timeout=20) as response:
            body = response.read().decode("utf-8")
            return response.status, json.loads(body)
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")
        try:
            payload = json.loads(body)
        except json.JSONDecodeError:
            payload = {"ok": False, "error": body or str(exc)}
        return exc.code, payload
    except Exception as exc:
        return 0, {"ok": False, "error": str(exc)}


