class OperatorApprovalView(discord.ui.View):
    def __init__(self, approval_id: str):
        super().__init__(timeout=300)
        self.approval_id = approval_id

    async def _decide(self, interaction: discord.Interaction, action: str):
        if ALLOWED_USER_ID and interaction.user.id != ALLOWED_USER_ID:
            await interaction.response.send_message("Not authorized.", ephemeral=True)
            return
        status_code, payload = await asyncio.to_thread(
            operator_request,
            "POST",
            "/api/operator/approval",
            {"id": self.approval_id, "action": action, "approver": str(interaction.user)},
        )
        ok = payload.get("ok")
        text = f"{'Accepted' if ok else 'Failed'} `{action}` for `{self.approval_id}` · status `{status_code}`"
        await interaction.response.send_message(text, ephemeral=True)

    @discord.ui.button(label="Approve", style=discord.ButtonStyle.success)
    async def approve_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        await self._decide(interaction, "approve")

    @discord.ui.button(label="Deny", style=discord.ButtonStyle.danger)
    async def deny_button(self, interaction: discord.Interaction, button: discord.ui.Button):
        await self._decide(interaction, "deny")


def build_operator_inspect_embed(project: str, status_code: int, payload: dict) -> discord.Embed:
    """Format inspect output for Discord without dumping raw JSON."""
    ok = bool(payload.get("ok"))
    color = 0x22c55e if ok else 0xef4444
    title = f"🔎 Operator Inspect — {project}"
    embed = discord.Embed(title=title, color=color, timestamp=datetime.utcnow())
    if not ok:
        embed.description = f"Request failed `{status_code or 'n/a'}`: {payload.get('error', 'unknown error')}"
        available = payload.get("availableProjects")
        if available:
            embed.add_field(name="Available projects", value=", ".join(f"`{p}`" for p in available), inline=False)
        return embed

    tree_entries = payload.get("tree", {}).get("entries", [])
    tree_lines = []
    for item in tree_entries[:16]:
        prefix = "📁" if item.get("type") == "dir" else "📄"
        tree_lines.append(f"{prefix} `{item.get('path', '')}`")
    tree_value = "\n".join(tree_lines) or "No visible files."
    if len(tree_entries) > 16:
        tree_value += f"\n… {len(tree_entries) - 16} more"

    status_short = payload.get("git", {}).get("statusShort") or "clean"
    log_lines = str(payload.get("git", {}).get("logOneline") or "").splitlines()[:5]
    counts = payload.get("fileCountsByExtension") or {}
    count_lines = [f"`{ext}` {count}" for ext, count in list(counts.items())[:10]]
    safety = payload.get("safety", {})

    embed.add_field(name="Root", value=f"`{payload.get('root', 'unknown')}`", inline=False)
    embed.add_field(name="Git status", value=f"```text\n{status_short[:950]}\n```", inline=False)
    embed.add_field(name="Recent commits", value="```text\n" + ("\n".join(log_lines) or "No git log available.")[:950] + "\n```", inline=False)
    embed.add_field(name="Tree preview", value=tree_value[:1024], inline=False)
    embed.add_field(name="File counts", value=("\n".join(count_lines) or "No files counted.")[:1024], inline=True)
    embed.add_field(
        name="Safety",
        value=(
            f"Mode: `{safety.get('mode', 'read-only')}`\n"
            f"Registry locked: `{bool(safety.get('registryLocked'))}`\n"
            f"Arbitrary commands: `{bool(safety.get('arbitraryCommands'))}`"
        ),
        inline=True,
    )
    return embed


